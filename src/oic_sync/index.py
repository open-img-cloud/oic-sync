"""The openimages.cloud catalog index (schema oic-index/v1).

The index is generated by the website build (oic-website, src/lib/catalog-index.ts) and lists,
for every image, the artifacts of its latest version with digests, sizes, the cosign bundle and
the complete Glance property set. The schema only gains fields over time; a breaking change
would bump it to oic-index/v2, which this version refuses.
"""

from __future__ import annotations

import math
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import Any

import httpx

DEFAULT_INDEX_URL = "https://images.openimages.cloud/index.json"
SCHEMA = "oic-index/v1"

# Service images (Octavia amphora, Manila service VM) are owned by an OpenStack service and
# imported with that service's procedure. They are only synced when named with --image.
SERVICE_IMAGES = frozenset({"octavia-amphora", "manila-service-image", "trove-guest-image", "cirros"})

# Index size cap: the real index is around 60 KiB.
MAX_INDEX_BYTES = 16 * 1024 * 1024

_HEX64 = re.compile(r"^[0-9a-f]{64}$")
_HEX128 = re.compile(r"^[0-9a-f]{128}$")


class IndexFormatError(ValueError):
    """The index is unreachable, malformed or of an unsupported schema."""


@dataclass(frozen=True)
class Signing:
    """Expected cosign keyless signer, as published in the index."""

    identity_regexp: str
    oidc_issuer: str


@dataclass(frozen=True)
class Artifact:
    variant: str | None
    version: str
    arch: str
    format: str
    firmware: str
    url: str
    sha256: str
    sha512: str | None
    size: int | None
    virtual_size: int | None
    bundle_url: str | None
    manifest_url: str | None
    signed: bool
    built_at: str | None
    glance_properties: Mapping[str, str] = field(default_factory=dict)

    @property
    def min_disk_gib(self) -> int | None:
        """Smallest root disk (GiB, rounded up) that fits the image."""
        if not self.virtual_size:
            return None
        return math.ceil(self.virtual_size / 2**30)


@dataclass(frozen=True)
class Image:
    id: str
    title: str
    status: str
    os_distro: str | None
    os_version: str | None
    login_user: str | None
    latest_version: str
    optional_glance_properties: Mapping[str, str]
    artifacts: tuple[Artifact, ...]


@dataclass(frozen=True)
class CatalogIndex:
    schema: str
    generated_at: str
    base_url: str
    signing: Signing
    images: tuple[Image, ...]

    def image(self, image_id: str) -> Image | None:
        return next((i for i in self.images if i.id == image_id), None)


@dataclass(frozen=True)
class Target:
    """One artifact to keep in sync: an image of the index, in one variant."""

    image: Image
    artifact: Artifact
    stable_name: str

    @property
    def label(self) -> str:
        """Short human label: debian-13, alpine-linux/uefi."""
        if self.artifact.variant:
            return f"{self.image.id}/{self.artifact.variant}"
        return self.image.id


def _str(d: Mapping[str, Any], key: str, where: str, *, optional: bool = False) -> str | None:
    value = d.get(key)
    if value is None and optional:
        return None
    if not isinstance(value, str) or not value:
        raise IndexFormatError(f"{where}: missing or invalid '{key}'")
    return value


def _int(d: Mapping[str, Any], key: str) -> int | None:
    value = d.get(key)
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise IndexFormatError(f"invalid '{key}': {value!r}")
    return value


def _props(value: Any, where: str) -> dict[str, str]:
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise IndexFormatError(f"{where}: glance properties must be an object")
    return {str(k): str(v) for k, v in value.items()}


def _parse_artifact(raw: Any, where: str) -> Artifact:
    if not isinstance(raw, dict):
        raise IndexFormatError(f"{where}: artifact must be an object")
    sha256 = (_str(raw, "sha256", where) or "").lower()
    if not _HEX64.match(sha256):
        raise IndexFormatError(f"{where}: sha256 is not 64 hex characters")
    sha512 = raw.get("sha512")
    if sha512 is not None:
        sha512 = str(sha512).lower()
        if not _HEX128.match(sha512):
            raise IndexFormatError(f"{where}: sha512 is not 128 hex characters")
    variant = raw.get("variant")
    if variant is not None and (not isinstance(variant, str) or not variant):
        raise IndexFormatError(f"{where}: invalid variant")
    url = _str(raw, "url", where)
    assert url is not None
    if not url.startswith("https://"):
        raise IndexFormatError(f"{where}: artifact url must be https")
    return Artifact(
        variant=variant,
        version=_str(raw, "version", where) or "",
        arch=_str(raw, "arch", where, optional=True) or "x86_64",
        format=_str(raw, "format", where, optional=True) or "qcow2",
        firmware=_str(raw, "firmware", where, optional=True) or "bios",
        url=url,
        sha256=sha256,
        sha512=sha512,
        size=_int(raw, "size"),
        virtual_size=_int(raw, "virtual_size"),
        bundle_url=_str(raw, "bundle_url", where, optional=True),
        manifest_url=_str(raw, "manifest_url", where, optional=True),
        signed=bool(raw.get("signed", False)),
        built_at=_str(raw, "built_at", where, optional=True),
        glance_properties=_props(raw.get("glance_properties"), where),
    )


def parse_index(data: Any) -> CatalogIndex:
    """Validate and convert the decoded index.json."""
    if not isinstance(data, dict):
        raise IndexFormatError("index is not a JSON object")
    schema = data.get("schema")
    if schema != SCHEMA:
        raise IndexFormatError(f"unsupported index schema {schema!r} (expected {SCHEMA})")
    signing_raw = data.get("signing")
    if not isinstance(signing_raw, dict):
        raise IndexFormatError("index has no 'signing' block")
    if signing_raw.get("type") != "cosign-keyless":
        raise IndexFormatError(f"unsupported signing type {signing_raw.get('type')!r}")
    signing = Signing(
        identity_regexp=_str(signing_raw, "certificate_identity_regexp", "signing") or "",
        oidc_issuer=_str(signing_raw, "certificate_oidc_issuer", "signing") or "",
    )
    try:
        re.compile(signing.identity_regexp)
    except re.error as e:
        raise IndexFormatError(f"signing: invalid identity regexp: {e}") from e

    images_raw = data.get("images")
    if not isinstance(images_raw, list):
        raise IndexFormatError("index has no 'images' list")
    images = []
    for raw in images_raw:
        if not isinstance(raw, dict):
            raise IndexFormatError("image entry must be an object")
        image_id = _str(raw, "id", "image") or ""
        artifacts_raw = raw.get("artifacts") or []
        if not isinstance(artifacts_raw, list):
            raise IndexFormatError(f"{image_id}: artifacts must be a list")
        artifacts = tuple(
            _parse_artifact(a, f"{image_id}[{n}]") for n, a in enumerate(artifacts_raw)
        )
        images.append(
            Image(
                id=image_id,
                title=_str(raw, "title", image_id) or image_id,
                status=_str(raw, "status", image_id, optional=True) or "stable",
                os_distro=_str(raw, "os_distro", image_id, optional=True),
                os_version=_str(raw, "os_version", image_id, optional=True),
                login_user=_str(raw, "login_user", image_id, optional=True),
                latest_version=_str(raw, "latest_version", image_id, optional=True) or "",
                optional_glance_properties=_props(raw.get("optional_glance_properties"), image_id),
                artifacts=artifacts,
            )
        )
    return CatalogIndex(
        schema=schema,
        generated_at=str(data.get("generated_at") or ""),
        base_url=str(data.get("base_url") or ""),
        signing=signing,
        images=tuple(images),
    )


def fetch_index(client: httpx.Client, url: str = DEFAULT_INDEX_URL) -> CatalogIndex:
    """Download and parse the index."""
    try:
        response = client.get(url)
        response.raise_for_status()
    except httpx.HTTPError as e:
        raise IndexFormatError(f"cannot fetch index {url}: {e}") from e
    if len(response.content) > MAX_INDEX_BYTES:
        raise IndexFormatError(f"index {url} is larger than {MAX_INDEX_BYTES} bytes")
    try:
        data = response.json()
    except ValueError as e:
        raise IndexFormatError(f"index {url} is not valid JSON: {e}") from e
    return parse_index(data)


def stable_name(image: Image, artifact: Artifact) -> str:
    """Name held by the newest version: the image title, plus the variant when there are several.

    Matches the osism export of the website: "Alpine Linux (UEFI)", "Debian 13".
    """
    if artifact.variant and len(image.artifacts) > 1:
        return f"{image.title} ({artifact.variant.upper()})"
    return image.title


def select_targets(
    index: CatalogIndex,
    images: Iterable[str] | None = None,
    variants: Iterable[str] | None = None,
    *,
    include_service: bool = False,
) -> list[Target]:
    """Artifacts to sync.

    images: ids to keep (all non-service images when empty); an unknown id is an error.
    variants: variant names to keep; artifacts without a variant are never filtered out.
    """
    wanted = list(dict.fromkeys(images or []))
    unknown = [i for i in wanted if index.image(i) is None]
    if unknown:
        raise IndexFormatError(f"unknown image id(s) in the index: {', '.join(unknown)}")
    variant_set = set(variants or [])
    targets: list[Target] = []
    for image in index.images:
        if wanted and image.id not in wanted:
            continue
        if not wanted and image.id in SERVICE_IMAGES and not include_service:
            continue
        for artifact in image.artifacts:
            if variant_set and artifact.variant and artifact.variant not in variant_set:
                continue
            targets.append(Target(image, artifact, stable_name(image, artifact)))
    return targets
